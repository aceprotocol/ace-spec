#!/usr/bin/env python3
"""Check that every SDK carries the specification's artifacts unchanged.

For each SDK:
  1. its copy of ``test-vectors.json`` is byte-identical to ``ace-spec/test-vectors.json`` and its tests read it;
  2. its bundled official manifests are byte-identical to ``ace-spec/profiles/*.json`` (TypeScript embeds them in
     ``src/profiles.generated.ts``; the check regenerates that file's text from the spec files);
  3. every constant in ``protocol-contract.json`` ``limits`` equals the SDK constant (``relayLimits`` bind relays only and
     are not checked here).

Every SDK given must pass (Swift bundles the manifests as the SwiftPM resources ``Sources/ACE/Profiles/<name>.json`` and
names its constants ``ACELimits.<camelCase>``, see SWIFT_NAMES). Usage, from ace-spec/:

    python3 scripts/check-sdk-artifacts.py --sdk-ts ../sdk-ts --sdk-py ../sdk-py --sdk-swift ../sdk-swift
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

SPEC = Path(__file__).resolve().parents[1]
MANIFESTS = ["core", "text", "commerce"]
SPEC_MANIFESTS = {m: (SPEC / "profiles" / f"{m}.json").read_bytes() for m in MANIFESTS}

ap = argparse.ArgumentParser()
ap.add_argument("--sdk-ts", type=Path, required=True)
ap.add_argument("--sdk-py", type=Path, required=True)
ap.add_argument("--sdk-swift", type=Path)
args = ap.parse_args()
for _k in ("sdk_ts", "sdk_py", "sdk_swift"):  # the interpreter below runs with cwd = the SDK
    if getattr(args, _k) is not None:
        setattr(args, _k, getattr(args, _k).resolve())

vectors = (SPEC / "test-vectors.json").read_bytes()
contract = json.loads((SPEC / "protocol-contract.json").read_text())
limits: dict[str, int] = dict(contract["limits"])


def eval_constants(source: str, pattern: str, charset: str = r"[A-Z0-9_ +*()\-]+", comment: str = r";|\s//") -> dict[str, int]:
    """Evaluate ``name = <integer expression>`` lines (numbers, _ separators, earlier names, + - * //)."""
    out: dict[str, int] = {}
    for name, expr in re.findall(pattern, source, re.M):
        expr = re.sub(r"(?<=\d)_(?=\d)", "", re.split(comment, expr)[0]).strip()
        if not re.fullmatch(charset, expr):
            continue
        try:
            out[name] = int(eval(expr, {"__builtins__": {}}, dict(out)))  # noqa: S307 - restricted to the grammar above
        except Exception:  # noqa: BLE001 - a constant built from something else is simply not comparable
            pass
    return out


def check_sdk(root: Path, fixture: Path, test_globs: list[str], manifest_check, constants: dict[str, int]) -> list[str]:
    errors: list[str] = []
    if not fixture.exists():
        errors.append(f"missing vectors copy {fixture}")
    elif fixture.read_bytes() != vectors:
        errors.append(f"stale vectors copy {fixture}")
    readers = [p for g in test_globs for p in root.glob(g) if "test-vectors.json" in p.read_text(errors="ignore")]
    if not readers:
        errors.append("no test reads test-vectors.json")
    errors += manifest_check()
    for k, v in limits.items():
        if constants.get(k) != v:
            errors.append(f"constant {k}: spec {v}, SDK {constants.get(k)}")
    return errors


# --- Python ----------------------------------------------------------------------------------------------------------

def py_manifests() -> list[str]:
    errs = []
    for m in MANIFESTS:
        p = args.sdk_py / "ace" / "manifests" / f"{m}.json"
        if not p.exists() or p.read_bytes() != SPEC_MANIFESTS[m]:
            errs.append(f"bundled manifest {m}.json differs from ace-spec/profiles")
    return errs


py_constants = eval_constants((args.sdk_py / "ace" / "limits.py").read_text(), r"^([A-Z][A-Z0-9_]*)\s*=\s*([^\n#]+)")
py_errors = check_sdk(args.sdk_py, args.sdk_py / "tests" / "fixtures" / "test-vectors.json", ["tests/*.py"], py_manifests, py_constants)
python = args.sdk_py / ".venv" / "bin" / "python"
if python.exists():  # the runtime values too, not just the source text
    code = "import json, ace.limits as l; print(json.dumps({k: getattr(l, k) for k in dir(l) if k.isupper()}))"
    rt = json.loads(subprocess.run([str(python), "-c", code], cwd=args.sdk_py, capture_output=True, text=True, check=True).stdout)
    py_errors += [f"runtime constant {k}: spec {v}, SDK {rt.get(k)}" for k, v in limits.items() if rt.get(k) != v]

# --- TypeScript ------------------------------------------------------------------------------------------------------

def ts_manifests() -> list[str]:
    out = "// Generated by scripts/gen-profiles.mjs from ace-spec/profiles/*.json. Do not edit.\n"
    out += "import type { ProfileManifest } from './manifest.js';\n\n"
    for m in MANIFESTS:
        data = json.loads(SPEC_MANIFESTS[m])
        out += f"export const {m.upper()}_MANIFEST: ProfileManifest = {json.dumps(data, indent=2, ensure_ascii=False)};\n\n"
    got = (args.sdk_ts / "src" / "profiles.generated.ts").read_text()
    return [] if got == out else ["src/profiles.generated.ts differs from ace-spec/profiles (run npm run gen:profiles)"]


ts_src = (args.sdk_ts / "src" / "limits.ts").read_text() + "\n" + (args.sdk_ts / "src" / "kel.ts").read_text()
ts_constants = eval_constants(ts_src, r"^export const ([A-Z][A-Z0-9_]*)(?::\s*number)?\s*=\s*([^\n]+)")
ts_errors = check_sdk(args.sdk_ts, args.sdk_ts / "tests" / "fixtures" / "test-vectors.json", ["tests/*.ts"], ts_manifests, ts_constants)

# --- Swift -----------------------------------------------------------------------------------------------------------

SWIFT_NAMES = {
    "TIMESTAMP_WINDOW_SECONDS": "timestampWindowSeconds", "OFFLINE_WINDOW_SECONDS": "offlineWindowSeconds",
    "MAX_PLAINTEXT_BYTES": "maxPlaintextBytes", "MAX_PACKET_BYTES": "maxPacketBytes",
    "MAX_PUBLISHED_AGENT_BYTES": "maxPublishedAgentBytes", "MAX_JSON_DEPTH": "maxJSONDepth", "MAX_TYPE_BYTES": "maxTypeBytes",
    "MAX_THREAD_ID_LENGTH": "maxThreadIdLength", "MAX_KEL_EVENTS": "maxKelEvents", "MAX_SIGNING_KEY_LIFETIME": "maxSigningKeyLifetime",
    "MAX_DESCRIPTOR_LIFETIME": "maxDescriptorSeconds", "MAX_DELEGATION_LIFETIME": "maxCredentialSeconds",
    "MAX_PERMIT_LIFETIME": "maxPermitSeconds", "PERMIT_RENEWAL_SECONDS": "permitRenewalSeconds",
    "MAX_RETAINED_PREKEYS": "maxPrekeys", "MAX_EXT_BYTES": "maxExtBytes", "MAX_NOTE_BYTES": "maxNoteBytes",
    "MAX_INBOX_PAGE": "maxInboxPage", "MAX_PAGE_BYTES": "maxPageBytes", "MAX_MANIFEST_BYTES": "maxManifestBytes",
    "MAX_SEND_BODY_BYTES": "maxSendBodyBytes", "DEFAULT_PAGE_LIMIT": "defaultPageLimit", "MIN_BLOCK_CAP": "minBlockCap",
    "STRANGER_ALLOWANCE": "strangerAllowance", "STRANGER_NETWORK_ALLOWANCE": "strangerNetworkAllowance",
    "PIN_REFRESH_INTERVAL_SECONDS": "pinRefreshIntervalSeconds", "MAX_FETCH_ATTEMPTS": "maxFetchAttempts",
    "MAX_PENDING_CONTACT_REQUESTS": "maxPendingContactRequests", "CONTACT_REQUEST_TTL_SECONDS": "contactRequestTTLSeconds",
    "MAX_STRANGER_KEL_EVENTS": "maxStrangerKelEvents", "MAX_STRANGER_DELEGATIONS": "maxStrangerDelegations",
}


def swift_manifests() -> list[str]:
    errs = []
    for m in MANIFESTS:
        p = args.sdk_swift / "Sources" / "ACE" / "Profiles" / f"{m}.json"
        if not p.exists() or p.read_bytes() != SPEC_MANIFESTS[m]:
            errs.append(f"bundled manifest Sources/ACE/Profiles/{m}.json differs from ace-spec/profiles/{m}.json")
    return errs


swift_errors: list[str] = []
if args.sdk_swift is not None:
    sw = args.sdk_swift
    # ACELimits: ``public static let name(: Int)? = <integer expression over earlier names>``
    sw_raw = eval_constants((sw / "Sources" / "ACE" / "Limits.swift").read_text(),
                            r"^\s*public static let ([a-z][A-Za-z0-9]*)\s*(?::\s*Int)?\s*=\s*([^\n]+)$", r"[A-Za-z0-9_ +*()\-]+", r"//")
    sw_constants = {spec: sw_raw[name] for spec, name in SWIFT_NAMES.items() if name in sw_raw}
    swift_errors = check_sdk(sw, sw / "Tests" / "ACETests" / "Fixtures" / "test-vectors.json", ["Tests/**/*.swift"],
                             swift_manifests, sw_constants)
    swift_errors += [f"no Swift name mapped for contract constant {k}" for k in limits if k not in SWIFT_NAMES]

failed = False
for name, errs in (("sdk-py", py_errors), ("sdk-ts", ts_errors), ("sdk-swift", swift_errors)):
    if name == "sdk-swift" and args.sdk_swift is None:
        print("sdk-swift: not checked (pass --sdk-swift)")
        continue
    if errs:
        print(f"{name}: FAIL")
        for e in errs:
            print(f"  - {e}")
        failed = True
    else:
        print(f"{name}: ok")
sys.exit(1 if failed else 0)
